from services.embedding_service import embed_text
import chromadb


# ============================================================
# 1. 测试问题
# ============================================================

query = "怎么查看项目操作记录？"


# ============================================================
# 2. 原始大 Chunk（C26）
# ============================================================

chunk_26 = """
第七章常见问题
Q1：忘记写日报怎么办？
A：系统支持3天内补录。超过3天需联系系统管理员补录。

Q2：AI报告生成需要多久？失败了怎么办？
A：通常3-5分钟，数据量大时约10分钟。

Q3：员工离职后数据怎么处理？
A：账号立即停用但数据保留。

Q4：项目状态可以手动改吗？
A：不可以，状态变更需走审批流。

Q5：毛利是怎么算的？
A：毛利=收入合同总额-支出合同总额。

Q6：日报可以删除吗？
A：仅本人可删除自己的日报。

Q7：上传附件最大多少？
A：单个文件不超过50MB。

Q8：登录失败怎么办？
A：确认密码是否正确。

Q9：怎么查看某个项目的操作记录？
A：进入项目详情→切换到【操作日志】Tab。
查看全公司操作记录用【系统日志】。
"""


# ============================================================
# 3. 拆出来的小 Chunk（Q9）
# ============================================================

chunk_q9 = """
Q：怎么查看某个项目的操作记录？
A：进入项目详情→切换到【操作日志】Tab。
查看全公司操作记录用【系统日志】。
"""


# ============================================================
# 4. 生成 Embedding
# ============================================================

print("正在生成 Embedding...")

query_embedding = embed_text(query)

chunk_26_embedding = embed_text(chunk_26)

chunk_q9_embedding = embed_text(chunk_q9)

print("Embedding 生成完成")


# ============================================================
# 5. 连接 Chroma
# ============================================================

client = chromadb.PersistentClient(
    path="data/chroma"
)


# ============================================================
# 6. 创建临时 Collection
# ============================================================

test_collection = client.get_or_create_collection(
    name="chunk_compare_test"
)


# ============================================================
# 7. 写入两个测试 Chunk
# ============================================================

test_collection.upsert(
    ids=[
        "chunk_26",
        "chunk_q9"
    ],
    documents=[
        chunk_26,
        chunk_q9
    ],
    embeddings=[
        chunk_26_embedding,
        chunk_q9_embedding
    ]
)


# ============================================================
# 8. 使用同一个 Query 进行检索
# ============================================================

result = test_collection.query(
    query_embeddings=[
        query_embedding
    ],
    n_results=2
)


# ============================================================
# 9. 输出结果
# ============================================================

print("\n" + "=" * 60)
print("Chunk 粒度对比实验")
print("=" * 60)

print(f"\n用户问题：{query}")

for rank, (document, distance, doc_id) in enumerate(
    zip(
        result["documents"][0],
        result["distances"][0],
        result["ids"][0]
    ),
    start=1
):

    print(f"\n===== Rank {rank} =====")
    print(f"ID：{doc_id}")
    print(f"Distance：{distance:.4f}")
    print("内容：")
    print(document)


# ============================================================
# 10. 删除临时 Collection
# ============================================================

client.delete_collection(
    name="chunk_compare_test"
)

print("\n" + "=" * 60)
print("实验完成，临时 Collection 已删除")
print("=" * 60)
